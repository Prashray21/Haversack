import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { runInit } from "../src/commands/init.js";
import { runSync } from "../src/commands/sync.js";
import { DEFAULT_CONFIG_FILE, MANIFEST_REL_PATH, loadProject } from "@haversackhq/core";

function capture() {
  const out: string[] = [];
  const err: string[] = [];
  return { stdout: (l: string) => out.push(l), stderr: (l: string) => err.push(l), out, err };
}

function init(cwd: string, io: ReturnType<typeof capture>) {
  return runInit({ cwd, ...io });
}

let dir: string | undefined;
afterEach(async () => {
  if (dir) await rm(dir, { recursive: true, force: true });
  dir = undefined;
});

/** Fixture repo: files are written, and the dir is a git repo (like a real one). */
async function makeRepo(files: Record<string, string>): Promise<string> {
  dir = path.join(tmpdir(), `runtime-init-${Date.now()}-${Math.random().toString(36).slice(2)}`);
  await mkdir(dir, { recursive: true });
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(dir, rel);
    await mkdir(path.dirname(abs), { recursive: true });
    await writeFile(abs, content);
  }
  const git = (args: string[]) =>
    execFileSync("git", ["-c", "user.email=t@local", "-c", "user.name=t", ...args], {
      cwd: dir,
      windowsHide: true,
    });
  git(["init", "-b", "main"]);
  return dir;
}

async function listFiles(root: string): Promise<string[]> {
  const names: string[] = [];
  async function walk(rel: string): Promise<void> {
    const entries = await readdir(path.join(root, rel), { withFileTypes: true });
    for (const entry of entries) {
      if (rel === "" && entry.name === ".git") continue; // metadata, not project content
      const child = rel === "" ? entry.name : `${rel}/${entry.name}`;
      if (entry.isDirectory()) await walk(child);
      else names.push(child);
    }
  }
  await walk("");
  return names.sort();
}

describe("haversack init", () => {
  it("empty repo: writes only a DRAFT project.yaml with empty context/rules", async () => {
    const repo = await makeRepo({});
    const io = capture();
    const code = await init(repo, io);

    expect(code, io.err.join("\n")).toBe(0);
    expect(io.out.join("\n")).toContain("DRAFT");
    expect(await listFiles(repo)).toEqual([DEFAULT_CONFIG_FILE]);

    const yaml = await readFile(path.join(repo, DEFAULT_CONFIG_FILE), "utf8");
    expect(yaml).toContain("# DRAFT generated by `haversack init`");
    expect(yaml).toMatch(/project: [a-z0-9]+(-[a-z0-9]+)*/); // derived from the directory name
    expect(yaml).toContain("context: []");
    expect(yaml).toContain("rules: []");

    // The draft is schema-valid by construction: it reloads cleanly.
    const loaded = await loadProject({ cwd: repo });
    expect(loaded.config.context).toEqual([]);
    expect(loaded.config.rules).toEqual([]);
  });

  it("repo with CLAUDE.md: MOVES it into context/ (it would conflict with the generated CLAUDE.md), and sync works afterwards", async () => {
    const repo = await makeRepo({ "CLAUDE.md": "# Legacy notes\n\nBe terse.\n" });
    const io = capture();
    const code = await init(repo, io);

    expect(code, io.err.join("\n")).toBe(0);
    expect(io.out.join("\n")).toContain("moved CLAUDE.md → context/existing-claude.md");
    expect(await readFile(path.join(repo, "context", "existing-claude.md"), "utf8")).toBe("# Legacy notes\n\nBe terse.\n");
    expect(await listFiles(repo)).toEqual([DEFAULT_CONFIG_FILE, "context/existing-claude.md"].sort()); // original gone
    const yaml = await readFile(path.join(repo, DEFAULT_CONFIG_FILE), "utf8");
    expect(yaml).toContain("  - context/existing-claude.md");
    expect(yaml).toContain("# Migrated from: CLAUDE.md");

    // F5.1 conflict rule: after migration, sync runs clean with no drift gate.
    const syncIo = capture();
    const syncCode = await runSync({ cwd: repo, yes: true, verify: false, force: false, ...syncIo });
    expect(syncCode, syncIo.err.join("\n")).toBe(0);
    expect(syncIo.out.join("\n")).toContain("wrote CLAUDE.md");
  });

  it("repo with AGENTS.md: copies it into rules/ (no generated counterpart yet — original stays)", async () => {
    const repo = await makeRepo({ "AGENTS.md": "Always run the tests.\n" });
    const io = capture();
    const code = await init(repo, io);

    expect(code, io.err.join("\n")).toBe(0);
    expect(io.out.join("\n")).toContain("copied AGENTS.md → rules/existing-agents.md");
    expect(await readFile(path.join(repo, "rules", "existing-agents.md"), "utf8")).toBe("Always run the tests.\n");
    expect(await listFiles(repo)).toEqual([DEFAULT_CONFIG_FILE, "AGENTS.md", "rules/existing-agents.md"].sort());
    const yaml = await readFile(path.join(repo, DEFAULT_CONFIG_FILE), "utf8");
    expect(yaml).toContain("  - rules/existing-agents.md");
  });

  it("repo with both files and .cursor/rules: migrates everything to the right halves", async () => {
    const repo = await makeRepo({
      "CLAUDE.md": "claude memory\n",
      "AGENTS.md": "agent instructions\n",
      ".cursor/rules/naming.mdc": "---\ndescription: naming\n---\nUse kebab-case.\n",
      ".cursor/rules/style.md": "Prefer small modules.\n",
    });
    const io = capture();
    const code = await init(repo, io);

    expect(code, io.err.join("\n")).toBe(0);
    // CLAUDE.md conflicts with a generated output → moved; the rest are copied.
    expect(io.out.join("\n")).toContain("moved CLAUDE.md → context/existing-claude.md");
    expect(io.out.join("\n")).toContain("copied AGENTS.md → rules/existing-agents.md");
    expect(await readFile(path.join(repo, "context", "existing-claude.md"), "utf8")).toBe("claude memory\n");
    expect(await readFile(path.join(repo, "rules", "existing-agents.md"), "utf8")).toBe("agent instructions\n");
    expect(await readFile(path.join(repo, "rules", "existing-cursor-naming.mdc"), "utf8")).toContain("Use kebab-case.");
    expect(await readFile(path.join(repo, "rules", "existing-cursor-style.md"), "utf8")).toBe("Prefer small modules.\n");
    // originals without a generated counterpart keep working for their tools
    expect(await listFiles(repo)).toContain("AGENTS.md");
    expect(await listFiles(repo)).not.toContain("CLAUDE.md");
    const yaml = await readFile(path.join(repo, DEFAULT_CONFIG_FILE), "utf8");
    expect(yaml).toContain("- context/existing-claude.md");
    expect(yaml).toContain("- rules/existing-agents.md");
    expect(yaml).toContain("- rules/existing-cursor-naming.mdc");
    expect(yaml).toContain("- rules/existing-cursor-style.md");

    // The draft references the migrated files and reloads cleanly.
    const loaded = await loadProject({ cwd: repo });
    expect(loaded.config.context).toEqual(["context/existing-claude.md"]);
    expect(loaded.config.rules).toEqual([
      "rules/existing-agents.md",
      "rules/existing-cursor-naming.mdc",
      "rules/existing-cursor-style.md",
    ]);
    expect(loaded.sources).toHaveLength(4);
  });

  it("re-running init refuses: the definition already exists, nothing changes (exit 2)", async () => {
    const repo = await makeRepo({ "CLAUDE.md": "memory\n" });
    const first = capture();
    expect(await init(repo, first)).toBe(0);
    const before = await listFiles(repo);

    const second = capture();
    const code = await init(repo, second);
    expect(code).toBe(2);
    expect(second.err.join("\n")).toContain("already exists");
    expect(second.err.join("\n")).toContain("does not modify existing definitions");
    expect(await listFiles(repo)).toEqual(before); // byte-identical tree
  });

  it("a repo that already has a hand-written project.yaml is refused (exit 2)", async () => {
    const repo = await makeRepo({
      "project.yaml": "runtime: 1\nproject: handmade\ntargets: [claude-code]\n",
      "AGENTS.md": "instructions\n",
    });
    const io = capture();
    const code = await init(repo, io);

    expect(code).toBe(2);
    expect(io.err.join("\n")).toContain("already exists");
    // the existing file is untouched
    expect(await readFile(path.join(repo, DEFAULT_CONFIG_FILE), "utf8")).toContain("handmade");
    expect(await listFiles(repo)).toEqual([DEFAULT_CONFIG_FILE, "AGENTS.md"].sort());
  });

  it("a broken existing project.yaml is refused, not bulldozed (exit 2)", async () => {
    const repo = await makeRepo({ "project.yaml": "runtime: 9\nproject: x\ntargets: [claude-code]\n" });
    const io = capture();
    const code = await init(repo, io);
    expect(code).toBe(2);
    expect(io.err.join("\n")).toContain("refuses to run while the existing project.yaml fails to load");
  });

  it("a secret in the ingested file blocks init: nothing is written (exit 3, redacted)", async () => {
    const fixtureToken = `ghp_${"D".repeat(36)}`; // runtime:allow-secret — scanner fixture
    const repo = await makeRepo({ "CLAUDE.md": `memory\nbootstrap credential: ${fixtureToken}\n` });
    const io = capture();
    const code = await init(repo, io);

    expect(code).toBe(3);
    const errText = io.err.join("\n");
    expect(errText).toContain("✘ secret detected in existing config files — nothing was written");
    expect(errText).toContain("CLAUDE.md:2");
    expect(errText).toContain("[REDACTED]");
    expect(errText).not.toContain(fixtureToken);
    expect(await listFiles(repo)).toEqual(["CLAUDE.md"]); // no draft, no migration
  });

  it("init leaves no manifest — drift tracking starts with the first sync", async () => {
    const repo = await makeRepo({});
    const io = capture();
    expect(await init(repo, io)).toBe(0);
    expect(await listFiles(repo)).not.toContain(MANIFEST_REL_PATH);
  });

  it("writes the draft with the `haversack: 1` spec key, never the legacy key (ADR 002)", async () => {
    const repo = await makeRepo({});
    const io = capture();
    expect(await init(repo, io)).toBe(0);
    const yaml = await readFile(path.join(repo, DEFAULT_CONFIG_FILE), "utf8");
    expect(yaml).toMatch(/^haversack: 1$/m);
    expect(yaml).not.toMatch(/^runtime:/m);
  });
});
