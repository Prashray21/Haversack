import { describe, expect, it } from "vitest";
import { CLAUDE_MD_PATH, claudeCodeAdapter } from "../src/adapters/claude-code.js";
import { hasGeneratedHeader } from "../src/adapters/header.js";
import { sha256Hex } from "../src/parse/files.js";
import { projectConfigSchema } from "../src/schema/project.js";
import type { CompiledProject } from "../src/adapters/types.js";
import type { ProjectConfig } from "../src/schema/project.js";
import type { SourceFile } from "../src/parse/load.js";

function compileProject(overrides: {
  config?: Partial<Parameters<typeof projectConfigSchema.parse>[0]>;
  sources?: SourceFile[];
}): CompiledProject {
  const config: ProjectConfig = projectConfigSchema.parse({
    runtime: 1,
    project: "acme-storefront",
    description: "Next.js storefront on Supabase for Acme.",
    context: ["context/product.md"],
    rules: ["rules/coding.md"],
    targets: ["claude-code"],
    ...overrides.config,
  });
  const sources: SourceFile[] =
    overrides.sources ??
    [
      { path: "context/product.md", content: "Product facts.\n", sha256: sha256Hex("Product facts.\n") },
      { path: "rules/coding.md", content: "Be terse.\n", sha256: sha256Hex("Be terse.\n") },
    ];
  return { config, sources, definitionHash: "test-hash" };
}

describe("claudeCodeAdapter", () => {
  it("generates exactly one file at CLAUDE.md", () => {
    const files = claudeCodeAdapter.generate(compileProject({}));
    expect(files).toHaveLength(1);
    expect(files[0]?.path).toBe(CLAUDE_MD_PATH);
  });

  it("starts with the generated header and is detected as ours", () => {
    const [file] = claudeCodeAdapter.generate(compileProject({}));
    const content = file?.content ?? "";
    expect(content.startsWith("<!-- GENERATED BY RUNTIME — DO NOT EDIT.")).toBe(true);
    expect(content).toContain("adapter claude-code v1");
    expect(hasGeneratedHeader(content)).toBe(true);
  });

  it("inlines title, description, context and rules in project.yaml order", () => {
    const [file] = claudeCodeAdapter.generate(compileProject({}));
    const content = file?.content ?? "";

    expect(content).toContain("# acme-storefront");
    expect(content).toContain("Next.js storefront on Supabase for Acme.");
    expect(content).toContain("## Project context");
    expect(content).toContain("### context/product.md");
    expect(content).toContain("Product facts.");
    expect(content).toContain("## Rules");
    expect(content).toContain("### rules/coding.md");
    expect(content).toContain("Be terse.");

    const contextIdx = content.indexOf("## Project context");
    const rulesIdx = content.indexOf("## Rules");
    expect(contextIdx).toBeGreaterThan(-1);
    expect(rulesIdx).toBeGreaterThan(contextIdx);
  });

  it("is deterministic (D5)", () => {
    const a = claudeCodeAdapter.generate(compileProject({}));
    const b = claudeCodeAdapter.generate(compileProject({}));
    expect(a).toEqual(b);
  });

  it("ends with exactly one trailing newline", () => {
    const [file] = claudeCodeAdapter.generate(compileProject({}));
    const content = file?.content ?? "";
    expect(content.endsWith("\n")).toBe(true);
    expect(content.endsWith("\n\n")).toBe(false);
  });

  it("omits sections with no files and the description line when absent", () => {
    const files = claudeCodeAdapter.generate(
      compileProject({
        config: { description: undefined, context: [], rules: [] },
        sources: [],
      }),
    );
    const content = files[0]?.content ?? "";
    expect(content).not.toContain("## Project context");
    expect(content).not.toContain("## Rules");
    expect(content).toContain("# acme-storefront");
  });
});
